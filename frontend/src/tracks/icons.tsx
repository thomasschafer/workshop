/**
 * A track's icon: a line drawing in the text's colour, so it follows the theme. Decorative, as
 * the track's name is always beside it. An icon this version doesn't know, such as from a newer
 * server, is left out rather than guessed at.
 */
export function TrackIcon({ icon, size = 18 }: { icon: IconName; size?: number }) {
  const shapes = ICONS[icon];
  if (shapes === undefined) return null;
  return (
    <svg
      class="track-icon"
      data-icon={icon}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      {shapes}
    </svg>
  );
}
