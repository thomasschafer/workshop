// Builds tree-sitter WASM grammars and copies Helix's query files into
// frontend/vendor/tree-sitter/<mode>/, driven by frontend/vendor/tree-sitter/manifest.json.
//
// Run via `mise run grammars`, or pass `--helix-dir /path/to/helix` to read Helix's queries
// from a local checkout instead of fetching them from GitHub.

import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

interface GrammarEntry {
  readonly helixLanguage: string;
  readonly grammar?: string;
  readonly git?: string;
  readonly rev?: string;
  readonly subpath?: string;
  readonly license?: string;
  /** Reuse another manifest entry's compiled WASM grammar (queries-only alias, e.g. rust-format-args-macro). */
  readonly reuseGrammar?: string;
  readonly injectionOnly?: boolean;
}

interface Manifest {
  readonly helixRepo: string;
  readonly helixCommit: string;
  readonly treeSitterCliVersion: string;
  readonly grammars: Readonly<Record<string, GrammarEntry>>;
}

const QUERY_FILES = [
  "highlights.scm",
  "locals.scm",
  "injections.scm",
  "textobjects.scm",
  "indents.scm",
  "tags.scm",
  "rainbows.scm",
] as const;

// Matches tree-house's `INHERITS_REGEX` in `tree-house/src/config.rs`.
const INHERITS_REGEX = /;+\s*inherits\s*:?\s*([a-z_,()-]+)\s*/g;

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const VENDOR_DIR = resolve(SCRIPT_DIR, "..", "vendor", "tree-sitter");
const MANIFEST_PATH = join(VENDOR_DIR, "manifest.json");

function run(command: string, args: readonly string[], cwd: string): void {
  execFileSync(command, [...args], { cwd, stdio: "inherit" });
}

function fetchGitRev(repo: string, rev: string, dest: string, sparsePath?: string): void {
  mkdirSync(dest, { recursive: true });
  run("git", ["init", "-q"], dest);
  run("git", ["remote", "add", "origin", repo], dest);
  if (sparsePath) {
    run("git", ["sparse-checkout", "init", "--cone"], dest);
    run("git", ["sparse-checkout", "set", sparsePath], dest);
    run("git", ["fetch", "--depth", "1", "--filter=blob:none", "origin", rev], dest);
  } else {
    run("git", ["fetch", "--depth", "1", "origin", rev], dest);
  }
  run("git", ["checkout", "-q", "FETCH_HEAD"], dest);
}

/**
 * Reads a Helix query file and expands any `; inherits:` directives recursively, matching
 * `tree_house::read_query`. Throws on inheritance cycles.
 */
function readHelixQuery(
  queriesRoot: string,
  language: string,
  filename: string,
  visiting: Set<string> = new Set(),
): string {
  const key = `${language}/${filename}`;
  if (visiting.has(key)) {
    throw new Error(`cyclic query inheritance involving ${key}`);
  }
  const filePath = join(queriesRoot, language, filename);
  if (!existsSync(filePath)) return "";
  const raw = readFileSync(filePath, "utf8");
  visiting.add(key);
  const resolved = raw.replace(INHERITS_REGEX, (_match, group: string) =>
    group
      .split(",")
      .map((parent) => `\n${readHelixQuery(queriesRoot, parent.trim(), filename, visiting)}\n`)
      .join(""),
  );
  visiting.delete(key);
  return resolved;
}

function copyLicenseFiles(sourceDir: string, outDir: string): string[] {
  const copied: string[] = [];
  for (const name of readdirSync(sourceDir).sort()) {
    if (/^(LICENSE|LICENCE|COPYING)([._-].*)?$/i.test(name)) {
      copyFileSync(join(sourceDir, name), join(outDir, name));
      copied.push(name);
    }
  }
  if (copied.length === 0) {
    throw new Error(`no license file found in ${sourceDir}`);
  }
  return copied;
}

function parseHelixDirArg(argv: readonly string[]): string | null {
  const index = argv.indexOf("--helix-dir");
  if (index === -1) return null;
  const value = argv[index + 1];
  if (!value) throw new Error("--helix-dir requires a path");
  return resolve(value);
}

function buildReadme(manifest: Manifest, licensesByMode: ReadonlyMap<string, string[]>): string {
  const rows = Object.entries(manifest.grammars)
    .map(([mode, entry]) => {
      const role = entry.injectionOnly ? "injection" : "editor mode";
      if (entry.reuseGrammar) {
        return `| \`${mode}\` | ${role} | \`${entry.helixLanguage}\` | reuses \`${entry.reuseGrammar}\` | — | see \`${entry.reuseGrammar}\` |`;
      }
      const files = (licensesByMode.get(mode) ?? []).map((f) => `\`${mode}/${f}\``).join(", ");
      const rev = entry.rev ? `\`${entry.rev.slice(0, 12)}\`` : "—";
      return `| \`${mode}\` | ${role} | \`${entry.helixLanguage}\` | ${entry.git ?? "—"} | ${rev} | ${entry.license ?? "—"} (${files}) |`;
    })
    .join("\n");

  return `# Tree-sitter grammars and Helix queries

These prebuilt WebAssembly grammars and query files are generated by
\`frontend/scripts/build-grammars.ts\` (run \`mise run grammars\`) from the pinned
revisions in \`manifest.json\`.

## Provenance

- Helix queries: ${manifest.helixRepo} at commit \`${manifest.helixCommit}\`
- Built with: \`tree-sitter-cli@${manifest.treeSitterCliVersion}\`

| Mode | Role | Helix language | Grammar repository | Revision | Grammar licence |
| --- | --- | --- | --- | --- | --- |
${rows}

## Licences

- The query files (\`*.scm\`) come from Helix and are licensed under the Mozilla
  Public License 2.0 (MPL-2.0).
- Each grammar's WebAssembly binary is built from its upstream repository above
  and keeps its own licence, copied alongside the grammar.
`;
}

function main(): void {
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8")) as Manifest;
  const localHelixDir = parseHelixDirArg(process.argv.slice(2));
  const workDir = mkdtempSync(join(tmpdir(), "workshop-grammars-"));

  try {
    let queriesRoot: string;
    if (localHelixDir) {
      queriesRoot = join(localHelixDir, "runtime", "queries");
      if (!existsSync(queriesRoot)) {
        throw new Error(`missing runtime/queries under ${localHelixDir}`);
      }
    } else {
      const helixClone = join(workDir, "helix");
      console.log(`Fetching Helix queries at ${manifest.helixCommit}...`);
      fetchGitRev(manifest.helixRepo, manifest.helixCommit, helixClone, "runtime/queries");
      queriesRoot = join(helixClone, "runtime", "queries");
    }

    const licensesByMode = new Map<string, string[]>();

    for (const [mode, entry] of Object.entries(manifest.grammars)) {
      const outDir = join(VENDOR_DIR, mode);
      rmSync(outDir, { recursive: true, force: true });
      mkdirSync(outDir, { recursive: true });

      if (entry.reuseGrammar) {
        if (!Object.hasOwn(manifest.grammars, entry.reuseGrammar)) {
          throw new Error(
            `${mode}: reuseGrammar ${JSON.stringify(entry.reuseGrammar)} not in manifest`,
          );
        }
        console.log(`\nCopying queries for ${mode} (reuses ${entry.reuseGrammar} grammar)...`);
      } else {
        if (!entry.grammar || !entry.git || !entry.rev || !entry.license) {
          throw new Error(
            `${mode}: grammar, git, rev and license are required unless reuseGrammar is set`,
          );
        }
        console.log(`\nBuilding ${mode} (${entry.grammar} @ ${entry.rev.slice(0, 12)})...`);
        const grammarCheckout = join(workDir, `grammar-${mode}`);
        fetchGitRev(entry.git, entry.rev, grammarCheckout);
        const buildDir = entry.subpath ? join(grammarCheckout, entry.subpath) : grammarCheckout;
        const wasmOut = join(outDir, `tree-sitter-${entry.grammar}.wasm`);

        run(
          "npx",
          [
            "-y",
            `tree-sitter-cli@${manifest.treeSitterCliVersion}`,
            "build",
            "--wasm",
            "-o",
            wasmOut,
          ],
          buildDir,
        );

        licensesByMode.set(mode, copyLicenseFiles(grammarCheckout, outDir));
      }

      for (const queryFile of QUERY_FILES) {
        const sourcePath = join(queriesRoot, entry.helixLanguage, queryFile);
        if (!existsSync(sourcePath)) continue;
        const resolved = readHelixQuery(queriesRoot, entry.helixLanguage, queryFile);
        writeFileSync(join(outDir, queryFile), resolved);
      }
    }

    writeFileSync(join(VENDOR_DIR, "README.md"), buildReadme(manifest, licensesByMode));
    console.log("\nDone.");
  } finally {
    rmSync(workDir, { recursive: true, force: true });
  }
}

main();
